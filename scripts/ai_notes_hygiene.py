from __future__ import annotations

"""Maintain an index of AI notes and flag potential staleness.

Notes live in `docs/ai/notes/` and are expected to include YAML frontmatter with:

- base_commit: <git sha>
- scope_paths: [ ... ] (optional)
- stale_policy.max_commits_since_base: <int> (optional; defaults to 30)

This script regenerates `docs/ai/notes/INDEX.md`.
"""

import argparse
import re
import subprocess
from dataclasses import dataclass
from pathlib import Path
from typing import Any


DEFAULT_MAX_COMMITS = 30
FRONTMATTER_RE = re.compile(r"^---\s*\n(.*?)\n---\s*\n", re.DOTALL)


@dataclass(frozen=True)
class NoteStatus:
    path: Path
    title: str
    date: str
    base_commit: str
    commits_since: int
    changed_in_scope: list[str]
    max_commits: int
    status: str


def project_root() -> Path:
    here = Path.cwd().resolve()
    for p in [here, *here.parents]:
        if (p / "pyproject.toml").exists():
            return p
    return here


def run_git(args: list[str], cwd: Path) -> str:
    out = subprocess.check_output(["git", *args], cwd=str(cwd))
    return out.decode("utf-8", errors="replace").strip()


def parse_frontmatter(md: str) -> dict[str, Any]:
    m = FRONTMATTER_RE.match(md)
    if not m:
        return {}
    body = m.group(1)
    data: dict[str, Any] = {}
    current_list_key: str | None = None
    for line in body.splitlines():
        if not line.strip():
            continue
        if re.match(r"^\s*-[ ]", line) and current_list_key:
            # ensure list
            if not isinstance(data.get(current_list_key), list):
                data[current_list_key] = []
            data[current_list_key].append(line.split("-", 1)[1].strip())
            continue
        current_list_key = None
        if ":" in line:
            k, v = line.split(":", 1)
            k = k.strip()
            v = v.strip().strip('"')
            if v == "":
                # list header
                data[k] = []
                current_list_key = k
            else:
                data[k] = v
    # normalize commit threshold key
    if "stale_policy.max_commits_since_base" in data:
        try:
            data["max_commits_since_base"] = int(
                data["stale_policy.max_commits_since_base"]
            )
        except ValueError:
            pass
    return data


def build_status(note_path: Path, repo_root: Path) -> NoteStatus:
    txt = note_path.read_text(encoding="utf-8", errors="replace")
    fm = parse_frontmatter(txt)
    title = str(fm.get("title", note_path.stem))
    date = str(fm.get("date", ""))
    base = str(fm.get("base_commit", ""))
    max_commits = int(fm.get("max_commits_since_base", DEFAULT_MAX_COMMITS))
    scope = fm.get("scope_paths", [])

    if not base:
        return NoteStatus(note_path, title, date, "", -1, [], max_commits, "UNKNOWN")

    try:
        commits_since = int(
            run_git(["rev-list", "--count", f"{base}..HEAD"], repo_root)
        )
    except Exception:
        commits_since = -1

    changed: list[str] = []
    if scope and commits_since >= 0:
        try:
            diff = run_git(
                ["diff", "--name-only", f"{base}..HEAD", "--", *scope], repo_root
            )
            changed = [l for l in diff.splitlines() if l.strip()]
        except Exception:
            changed = []

    if commits_since < 0:
        status = "UNKNOWN"
    elif changed:
        status = "STALE"
    elif commits_since > max_commits:
        status = "MAYBE_STALE"
    else:
        status = "FRESH"

    return NoteStatus(
        note_path, title, date, base, commits_since, changed, max_commits, status
    )


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        description="Regenerate docs/ai/notes/INDEX.md with staleness flags."
    )
    p.add_argument("--notes-dir", default="docs/ai/notes", help="Notes directory")
    p.add_argument("--out", default="docs/ai/notes/INDEX.md", help="Index output path")
    return p


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    repo_root = project_root()
    notes_dir = (repo_root / args.notes_dir).resolve()
    out_path = (repo_root / args.out).resolve()
    notes_dir.mkdir(parents=True, exist_ok=True)

    notes = sorted(
        [p for p in notes_dir.glob("*.md") if p.name != "INDEX.md"],
        key=lambda p: p.name.lower(),
    )
    statuses = [build_status(p, repo_root) for p in notes]

    lines: list[str] = []
    lines.append("# AI Notes Index (auto-generated)")
    lines.append("")
    lines.append(
        "This file is generated by `scripts/ai_notes_hygiene.py`. Do not edit manually."
    )
    lines.append("")
    lines.append("## Status legend")
    lines.append("")
    lines.append(
        "- **FRESH**: no scoped changes since base_commit and within commit threshold"
    )
    lines.append(
        "- **MAYBE_STALE**: exceeded commit threshold, but scoped files unchanged"
    )
    lines.append("- **STALE**: scoped files changed since base_commit")
    lines.append("- **UNKNOWN**: missing base_commit or git query failed")
    lines.append("")

    if not statuses:
        lines.append("(No notes found.)")
    else:
        for s in statuses:
            rel = s.path.relative_to(repo_root)
            extra = (
                f"commits_since={s.commits_since}"
                if s.commits_since >= 0
                else "commits_since=?"
            )
            base_short = s.base_commit[:10] if s.base_commit else "(none)"
            scope_flag = "scope_changed" if s.changed_in_scope else ""
            lines.append(
                f"- **{s.status}** `{rel}` — {s.title} (date={s.date or '?'}, base={base_short}, {extra}, max={s.max_commits}) {scope_flag}".rstrip()
            )
            if s.changed_in_scope:
                for ch in s.changed_in_scope[:10]:
                    lines.append(f"  - changed: `{ch}`")
                if len(s.changed_in_scope) > 10:
                    lines.append(f"  - … and {len(s.changed_in_scope) - 10} more")

    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
